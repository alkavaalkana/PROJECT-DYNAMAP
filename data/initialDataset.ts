function parseEnneagramRaw(raw: string): {
  core: EnneagramCore | null;
  instinct: InstinctCode | '';
} {
  const match = raw.trim().toUpperCase().match(/^(SP|SO|SX)([1-9])$/);
  if (!match) return { core: null, instinct: '' };
  return {
    instinct: match[1] as InstinctCode,
    core: Number(match[2]) as EnneagramCore,
  };
}

